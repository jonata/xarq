#!/usr/bin/env python3
"""Regenerates the Haiku resources: XarQ.rdef (signature, version, vector icon) and x-vnd.xara-xar.rdef (file type).

Haiku icons are HVIF, a compact binary vector format. There is no converter from SVG outside Icon-O-Matic,
so this encodes assets/logo/xarq-appicon.svg by hand on the 64-unit HVIF grid. Run it from any directory:
    python3 src/haiku/make_rdef.py
"""
import os
import struct

VERSION = (26, 10, 0)
SIGNATURE = "application/x-vnd.XarQ"
XAR_TYPE = "application/x-vnd.xara-xar"

PATH_CLOSED, PATH_NO_CURVES = 1 << 1, 1 << 3
GRADIENT_TRANSFORM, GRADIENT_NO_ALPHA = 1 << 1, 1 << 2
STYLE_SOLID, STYLE_GRADIENT = 1, 2
SHAPE_PATH_SOURCE = 10
SHAPE_HAS_TRANSFORMERS = 1 << 4
TRANSFORMER_STROKE = 23
CAP_ROUND = 2 << 4


def coord(v):
    """HVIF coordinate: one byte for whole numbers in -32..95, otherwise two bytes in 1/102 steps."""
    if v == int(v) and -32 <= v <= 95:
        return bytes([int(v) + 32])
    fixed = int(round((v + 128.0) * 102.0))
    return bytes([0x80 | (fixed >> 8), fixed & 0xFF])


def float24(v):
    if v == 0:
        return b"\0\0\0"
    bits = struct.unpack("<I", struct.pack("<f", v))[0]
    sign, exponent, mantissa = bits >> 31, ((bits >> 23) & 0xFF) - 127, bits & 0x7FFFFF
    packed = (sign << 23) | ((exponent + 32) << 17) | (mantissa >> 6)
    return packed.to_bytes(3, "big")


def solid(r, g, b, a=255):
    return bytes([STYLE_SOLID, r, g, b, a])


def gradient(kind, matrix, stops, opaque):
    """kind 0 is linear, 1 circular. A gradient spans -64..64 in its own space; matrix places it on the icon."""
    flags = GRADIENT_TRANSFORM | (GRADIENT_NO_ALPHA if opaque else 0)
    out = bytes([STYLE_GRADIENT, kind, flags, len(stops)])
    out += b"".join(float24(m) for m in matrix)
    for offset, rgba in stops:
        out += bytes([offset]) + bytes(rgba[:3] if opaque else rgba)
    return out


def polyline(points, closed=False):
    out = bytes([PATH_NO_CURVES | (PATH_CLOSED if closed else 0), len(points)])
    return out + b"".join(coord(x) + coord(y) for x, y in points)


def round_rect(x0, y0, x1, y1, r):
    """Clockwise rounded rectangle: every node carries position, in-handle and out-handle."""
    k = r * 0.5523
    nodes = [
        ((x0 + r, y0), (x0 + r - k, y0), (x0 + r, y0)), ((x1 - r, y0), (x1 - r, y0), (x1 - r + k, y0)),
        ((x1, y0 + r), (x1, y0 + r - k), (x1, y0 + r)), ((x1, y1 - r), (x1, y1 - r), (x1, y1 - r + k)),
        ((x1 - r, y1), (x1 - r + k, y1), (x1 - r, y1)), ((x0 + r, y1), (x0 + r, y1), (x0 + r - k, y1)),
        ((x0, y1 - r), (x0, y1 - r + k), (x0, y1 - r)), ((x0, y0 + r), (x0, y0 + r), (x0, y0 + r - k)),
    ]
    out = bytes([PATH_CLOSED, len(nodes)])
    for node in nodes:
        for x, y in node:
            out += coord(x) + coord(y)
    return out


def shape(style, path, stroke_width=None):
    out = bytes([SHAPE_PATH_SOURCE, style, 1, path])
    if stroke_width is None:
        return out + bytes([0])
    return out + bytes([SHAPE_HAS_TRANSFORMERS, 1, TRANSFORMER_STROKE, stroke_width + 128, CAP_ROUND, 4])


def icon():
    vertical = (0, 0.5, -0.5, 0, 32, 32)
    styles = [
        gradient(0, vertical, [(0, (0x20, 0x24, 0x2C, 255)), (255, (0x0C, 0x0D, 0x10, 255))], True),
        gradient(1, (0.44, 0, 0, 0.44, 32, 27), [(0, (0x2D, 0x6F, 0xF7, 115)), (255, (0x2D, 0x6F, 0xF7, 0))], False),
        solid(0x8B, 0x6B, 0xFF),
        solid(0x4C, 0x86, 0xFF),
        solid(0x0C, 0x0D, 0x10),
    ]
    paths = [
        round_rect(2, 2, 62, 62, 14),
        polyline([(44, 23), (25, 42)]),
        polyline([(25, 23), (49, 47)]),
        polyline([(41, 20), (47, 20), (47, 26), (41, 26)], closed=True),
    ]
    shapes = [
        shape(0, 0),                     # dark tile
        shape(1, 0),                     # blue glow
        shape(2, 1, stroke_width=6),     # violet stroke of the X
        shape(3, 2, stroke_width=6),     # blue stroke of the X
        shape(4, 3),                     # node handle on the violet stroke
        shape(2, 3, stroke_width=1),
    ]
    out = b"ncif"
    for items in (styles, paths, shapes):
        out += bytes([len(items)]) + b"".join(items)
    return out


def hex_lines(data, width=32):
    return "\n".join('\t$"%s"' % data[i:i + width].hex().upper() for i in range(0, len(data), width))


RDEF = """// Generated by make_rdef.py: edit that script rather than this file.
resource app_signature "%s";

resource app_flags B_MULTIPLE_LAUNCH;

resource app_version {
	major  = %d,
	middle = %d,
	minor  = %d,
	variety = B_APPV_ALPHA,
	internal = 0,
	short_info = "XarQ",
	long_info = "XarQ vector illustration and page layout"
};

resource file_types message {
	"types" = "application/x-vnd.xara-xar",
	"types" = "image/svg+xml",
	"types" = "image/png",
	"types" = "image/jpeg"
};

resource vector_icon {
%s
};
"""

XAR_TYPE_RDEF = """// Generated by make_rdef.py: edit that script rather than this file.
// The Haiku file type for Xara documents, compiled with rc and stored in mime_db with resattr. Haiku's stock
// database reads .xar as the unrelated eXtensible ARchive, so these are recognised by their magic.
resource(0, "META:TYPE") "%s";

resource(1, "META:SNIFF_RULE") #'CSTR' array {
	"0.90 ('XARA\\\\243\\\\243')"
};

resource(2, "META:EXTENS") message(234) {
	"extensions" = "xar",
	"type" = "%s"
};

resource(3, "META:S:DESC") #'MSDC' "Xara document";

resource(4, "META:L:DESC") #'MLDC' "Xara vector document";

resource(5, "META:PREF_APP") #'MSIG' "%s";

resource(6, "BEOS:TYPE") #'MIMS' "application/x-vnd.Be-meta-mime";

resource(7, "META:ICON") #'VICN' array {
%s
};
"""

here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "XarQ.rdef"), "w") as out:
    out.write(RDEF % (SIGNATURE, *VERSION, hex_lines(icon())))
with open(os.path.join(here, "x-vnd.xara-xar.rdef"), "w") as out:
    out.write(XAR_TYPE_RDEF % (XAR_TYPE, XAR_TYPE, SIGNATURE, hex_lines(icon())))
print(here, len(icon()), "byte icon")
